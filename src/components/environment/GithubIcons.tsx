export type OcticonName = keyof typeof OCTICON_PATHS;

export function Octicon({
  name,
  size = 16,
  className,
  label,
}: {
  name: OcticonName;
  size?: number;
  className?: string;
  label?: string;
}) {
  return (
    <svg
      viewBox="0 0 16 16"
      width={size}
      height={size}
      fill="currentColor"
      className={className}
      role={label ? 'img' : undefined}
      aria-label={label}
      aria-hidden={label ? undefined : true}
    >
      <path d={OCTICON_PATHS[name]} />
    </svg>
  );
}

interface IconProps {
  size?: number;
  className?: string;
}

