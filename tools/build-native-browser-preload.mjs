// Bundles electron/nativeBrowserPreload/ into the single file Electron loads as
// the browser preload. Sandboxed preloads cannot require() sibling modules at
// runtime, so the source is split for maintainability and inlined here.
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const entry = join(root, 'electron/nativeBrowserPreload/index.js');
const outfile = join(root, 'electron/nativeBrowserPreload.cjs');

execFileSync(
  join(root, 'node_modules/.bin/esbuild'),
  [
    entry,
    '--bundle',
    '--platform=node',
    '--format=cjs',
    '--target=node22',
    '--external:electron',
    `--outfile=${outfile}`,
  ],
  { stdio: ['ignore', 'ignore', 'inherit'] },
);

const banner = `// GENERATED by tools/build-native-browser-preload.mjs from
// electron/nativeBrowserPreload/. Edit those modules, not this file.\n`;
const prettierConfig = await resolveConfig(outfile);
writeFileSync(
  outfile,
  await format(banner + readFileSync(outfile, 'utf8'), { ...prettierConfig, filepath: outfile }),
);
